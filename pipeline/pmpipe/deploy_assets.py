#!/usr/bin/env python3
"""Deploy-asset generator for the C++ framework (runs in the sim2real py3.10 venv; no GPU, no robot).

Generalised from deploy/partymimic_cpp/dev/export_assets.py (the SSB generator, which asserts frozen SSB hashes): same files, same formats,
same parameter resolution - but the policy / yaml / motion are inputs. Regression: for the SSB robust_d it12000 inputs this reproduces
assets/SHA256SUMS of deploy/partymimic_cpp byte for byte (pipeline/tests/test_deploy_assets.py).

  assets/policy.onnx        copied byte-for-byte
  assets/policy_params.txt  joint order, default pose, action scale, kp/kd (regex-expanded from the exporter yaml), robot limits (sim2real G1 cfg)
  assets/motion.bin         reference motion (joint_pos, joint_vel, pelvis pos/quat per 50 Hz frame; float16-rounded like the Python deployment stack)
  assets/fk_chain.txt       offline FK chain root->anchor (empty: anchor == floating base pelvis)
  assets/SHA256SUMS
usage: S2R_PY deploy_assets.py --onnx X.onnx --yaml X.yaml --motion dance.npz --out DIR [--provenance TEXT]
"""
import argparse
import hashlib
import os
import shutil
import struct
import sys
from pathlib import Path

import numpy as np

for _k in ("ALL_PROXY", "all_proxy", "HTTP_PROXY", "http_proxy", "HTTPS_PROXY", "https_proxy", "NO_PROXY", "no_proxy"):
    os.environ.pop(_k, None)
S2R = Path(os.environ.get("PM_SIM2REAL", Path(__file__).resolve().parents[3] / "sim2real_party_p0_patched"))
CACHE = Path(os.environ.get("PM_P2_CACHE", Path(__file__).resolve().parents[2] / "results/p2/run_20261119/sim2real_adapter/cache"))
for k, v in {"HF_HOME": CACHE / "huggingface", "HF_HUB_CACHE": CACHE / "huggingface/hub", "HUGGINGFACE_HUB_CACHE": CACHE / "huggingface/hub",
             "HF_HUB_OFFLINE": "1", "HF_DATASETS_OFFLINE": "1"}.items():
    os.environ.setdefault(k, str(v))
sys.path.insert(0, str(S2R))


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def fmt(a):
    return " ".join(repr(float(x)) for x in np.asarray(a, np.float64).reshape(-1))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--onnx", required=True); ap.add_argument("--yaml", required=True); ap.add_argument("--motion", required=True); ap.add_argument("--out", required=True)
    ap.add_argument("--provenance", default="")
    a = ap.parse_args()
    import yaml
    from sim2real.config.robots import get_robot_cfg
    from sim2real.utils.strings import resolve_matching_names_values
    cfg = get_robot_cfg("g1")
    names = list(cfg.joint_names)
    y = yaml.safe_load(Path(a.yaml).read_text())
    assert list(y["joint_names_simulation"]) == names == list(y["policy_joint_names"]), "joint order differs between yaml and robot cfg"

    def expand(d, order):
        idx, _, v = resolve_matching_names_values(d, order, preserve_order=True, strict=False)
        o = np.zeros(len(order)); o[idx] = v
        return o

    def expand_nan(d):
        idx, _, v = resolve_matching_names_values(dict(d), names, preserve_order=True, strict=False)
        o = np.full(len(names), np.nan); o[idx] = v
        return o

    default = expand(y["default_joint_pos"], names)
    scale = np.ones(len(names)); ids, _, v = resolve_matching_names_values(y["action_scale"], names, preserve_order=True); scale[ids] = v
    kp, kd = expand(y["joint_kp"], names), expand(y["joint_kd"], names)
    lo, hi, vel, eff = (expand_nan(getattr(cfg, k)) for k in ("joint_pos_lower_limit", "joint_pos_upper_limit", "joint_velocity_limit", "joint_effort_limit"))
    assert not (np.isnan(lo).any() or np.isnan(hi).any() or np.isnan(eff).any())
    fut = list(y["motion"]["future_steps"])
    hist = {k: list(v.values())[0].get("history_steps") for k, v in y["observation"].items()}
    obs = {k: list(v.values())[0]["_target_"] for k, v in y["observation"].items()}
    assert obs == {"proprio": "supermimic.proprio_history", "root_quat_hist": "supermimic.root_quat_history",
                   "ref_joint_pos": "supermimic.ref_joint_pos", "ref_root": "supermimic.ref_anchor"}, obs
    assert y["motion"]["root_body_name"] == "pelvis" and y["motion"]["anchor_body_name"] == "pelvis", "only pelvis-anchored policies are supported by the C++ FK stub"
    A = Path(a.out); A.mkdir(parents=True, exist_ok=True)
    ysha = sha(a.yaml)
    lines = ["# generated by dev/export_assets.py from the frozen P2 yaml + sim2real G1 robot cfg (do not edit)",
             f"# yaml_sha256 {ysha}", "format 1", f"joint_names {len(names)} " + " ".join(names),
             f"default_pos {len(names)} {fmt(default)}", f"action_scale {len(names)} {fmt(scale)}", f"kp {len(names)} {fmt(kp)}", f"kd {len(names)} {fmt(kd)}",
             f"pos_lo {len(names)} {fmt(lo)}", f"pos_hi {len(names)} {fmt(hi)}", f"vel_lim {len(names)} {fmt(np.where(np.isnan(vel), 0.0, vel))}",
             f"vel_known {len(names)} " + " ".join("0" if np.isnan(x) else "1" for x in vel), f"effort_lim {len(names)} {fmt(eff)}",
             f"history_steps {hist['proprio']}", f"future_steps {len(fut)} " + " ".join(str(int(s)) for s in fut), "rl_rate_hz 50"]
    (A / "policy_params.txt").write_text("\n".join(lines) + "\n")
    shutil.copyfile(a.onnx, A / "policy.onnx")

    z = np.load(a.motion, allow_pickle=True)
    assert [str(x) for x in z["joint_names"]][:29] == names, "motion joint order != robot"
    bi = list(z["body_names"]).index("pelvis")
    f16 = lambda x: np.asarray(x, np.float16).astype(np.float32)  # the deployed Python stack stores the reference as float16
    jp, jv, rp, rq = f16(z["joint_pos"]), f16(z["joint_vel"]), f16(z["body_pos_w"][:, bi]), f16(z["body_quat_w"][:, bi])
    T, fps = len(jp), float(z["fps"][0])
    with open(A / "motion.bin", "wb") as f:
        f.write(b"PMMO"); f.write(struct.pack("<iif", T, len(names), fps))
        for arr in (jp, jv, rp, rq):
            f.write(np.ascontiguousarray(arr, "<f4").tobytes())
    (A / "fk_chain.txt").write_text("# offline FK chain root(pelvis) -> pelvis: per link  <joint|-> body_quat_wxyz(4) joint_axis(3)\nanchor pelvis\n")
    prov = a.provenance or f"yaml {ysha}  motion {sha(a.motion)}"
    (A / "SHA256SUMS").write_text("".join(f"{sha(A / n)}  {n}\n" for n in ("policy.onnx", "policy_params.txt", "motion.bin", "fk_chain.txt")) + f"# provenance (dev inputs, not shipped): {prov}\n")
    print(f"OK frames {T} fps {fps} onnx {sha(A / 'policy.onnx')[:12]} params {sha(A / 'policy_params.txt')[:12]} motion {sha(A / 'motion.bin')[:12]}")


if __name__ == "__main__":
    main()
