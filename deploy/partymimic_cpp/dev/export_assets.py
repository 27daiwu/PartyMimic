#!/usr/bin/env python3
"""DEV PC ONLY (never shipped). Pre-processes everything the C++ runtime needs so that no Python/MuJoCo/PyTorch/XML is needed on the robot.

  assets/policy.onnx        frozen P2 ONNX (copied byte-for-byte, sha256 checked)
  assets/policy_params.txt  joint order, default pose, action scale, kp/kd (regex-expanded from the frozen yaml), robot joint/velocity/effort limits
  assets/motion.bin         SSB reference motion (joint_pos, joint_vel, pelvis pos/quat per 50 Hz frame) taken from the SAME loader the Python stack used
  assets/fk_chain.txt       offline kinematic chain root->anchor body (empty when anchor == floating base, as in the frozen P2 yaml: anchor_body_name=pelvis)
  assets/SHA256SUMS         hashes of the frozen inputs
  dev/fixtures/parity_ref.bin, dev/fixtures/fk_ref.bin   golden data for dev-only checks

usage:  <sim2real venv python> dev/export_assets.py
"""
import hashlib, json, os, shutil, struct, sys
from pathlib import Path
import numpy as np

HERE = Path(__file__).resolve().parents[1]
REPO = HERE.parents[1]
P2 = REPO / "results/p2/run_20261119"
ART = P2 / "artifacts"
SIM2REAL = Path(os.environ.get("FT_SIM2REAL", REPO.parent / "sim2real_party_p0_patched"))
sys.path.insert(0, str(SIM2REAL))
CACHE = P2 / "sim2real_adapter/cache"
for _k in ("ALL_PROXY","all_proxy","HTTP_PROXY","http_proxy","HTTPS_PROXY","https_proxy","NO_PROXY","no_proxy"):
    os.environ.pop(_k, None)
for k, v in {"HF_HOME": CACHE / "huggingface", "HF_HUB_CACHE": CACHE / "huggingface/hub", "HUGGINGFACE_HUB_CACHE": CACHE / "huggingface/hub",
             "HF_HUB_OFFLINE": "1", "HF_DATASETS_OFFLINE": "1"}.items():
    os.environ[k] = str(v)

FROZEN = {"policy.onnx": "0c51d5f26de2698ec6922cb3005410f714a1ac573b665b22b134be389fb1b9a6",
          "ssb_motion.npz": "d4d4d936a670d54e1cca5bf0f059f1ee9fc79f17733a64a859b1e929d6084cc6",
          "policy.yaml": "1b52fe3069476ddb6947a198854faf33b6af0a25efee46d8b8859ea7dbbfebac"}


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def fmt(a):
    return " ".join(repr(float(x)) for x in np.asarray(a, np.float64).reshape(-1))


def main():
    onnx, yaml_p, motion_npz = ART / "ssb_seed0_it1500.onnx", ART / "ssb_seed0_it1500.yaml", P2 / "sim2real_adapter/legacy_ssb/motion.npz"
    for name, p in (("policy.onnx", onnx), ("policy.yaml", yaml_p), ("ssb_motion.npz", motion_npz)):
        assert sha(p) == FROZEN[name], f"{name} is not the frozen P2 artifact"
    import yaml
    from sim2real.config.robots import get_robot_cfg
    from sim2real.utils.strings import resolve_matching_names_values
    from sim2real.rl_policy.utils.motion import MotionDataset, motion_dataset_first_motion
    cfg = get_robot_cfg("g1"); names = list(cfg.joint_names)
    y = yaml.safe_load(yaml_p.read_text())
    assert list(y["joint_names_simulation"]) == names == list(y["policy_joint_names"]), "joint order differs between yaml and robot cfg"

    def expand(d, order):
        idx, _, v = resolve_matching_names_values(d, order, preserve_order=True, strict=False)
        o = np.zeros(len(order)); o[idx] = v; return o

    def expand_nan(d):
        idx, _, v = resolve_matching_names_values(dict(d), names, preserve_order=True, strict=False)
        o = np.full(len(names), np.nan); o[idx] = v; return o

    default = expand(y["default_joint_pos"], names)
    # action_scale: BasePolicy resolves it against policy_joint_names with strict matching
    scale = np.ones(len(names)); ids, _, v = resolve_matching_names_values(y["action_scale"], names, preserve_order=True); scale[ids] = v
    kp, kd = expand(y["joint_kp"], names), expand(y["joint_kd"], names)
    lo, hi, vel, eff = (expand_nan(getattr(cfg, k)) for k in ("joint_pos_lower_limit", "joint_pos_upper_limit", "joint_velocity_limit", "joint_effort_limit"))
    assert not (np.isnan(lo).any() or np.isnan(hi).any() or np.isnan(eff).any())
    fut = list(y["motion"]["future_steps"]); hist = {k: list(v.values())[0].get("history_steps") for k, v in y["observation"].items()}
    obs = {k: list(v.values())[0]["_target_"] for k, v in y["observation"].items()}
    assert obs == {"proprio": "supermimic.proprio_history", "root_quat_hist": "supermimic.root_quat_history",
                   "ref_joint_pos": "supermimic.ref_joint_pos", "ref_root": "supermimic.ref_anchor"}, obs
    assert y["motion"]["root_body_name"] == "pelvis" and y["motion"]["anchor_body_name"] == "pelvis"
    A = HERE / "assets"; A.mkdir(exist_ok=True)
    lines = ["# generated by dev/export_assets.py from the frozen P2 yaml + sim2real G1 robot cfg (do not edit)",
             f"# yaml_sha256 {FROZEN['policy.yaml']}", "format 1", f"joint_names {len(names)} " + " ".join(names),
             f"default_pos {len(names)} {fmt(default)}", f"action_scale {len(names)} {fmt(scale)}", f"kp {len(names)} {fmt(kp)}", f"kd {len(names)} {fmt(kd)}",
             f"pos_lo {len(names)} {fmt(lo)}", f"pos_hi {len(names)} {fmt(hi)}", f"vel_lim {len(names)} {fmt(np.where(np.isnan(vel), 0.0, vel))}",
             f"vel_known {len(names)} " + " ".join("0" if np.isnan(x) else "1" for x in vel), f"effort_lim {len(names)} {fmt(eff)}",
             f"history_steps {hist['proprio']}", f"future_steps {len(fut)} " + " ".join(str(int(s)) for s in fut), "rl_rate_hz 50"]
    (A / "policy_params.txt").write_text("\n".join(lines) + "\n")
    shutil.copyfile(onnx, A / "policy.onnx")

    ds = motion_dataset_first_motion(MotionDataset.create_from_path(str(motion_npz), robot_cfg=cfg))
    T = int(ds.num_steps); md = ds.get_slice(np.zeros(T, dtype=int), np.arange(T), np.array([0]))
    r = list(ds.body_names).index("pelvis"); fps = float(np.load(motion_npz)["fps"][0])
    jp = np.asarray(md.joint_pos[:, 0], np.float32); jv = np.asarray(md.joint_vel[:, 0], np.float32)
    rp = np.asarray(md.body_pos_w[:, 0, r], np.float32); rq = np.asarray(md.body_quat_w[:, 0, r], np.float32)
    assert list(ds.joint_names)[:29] == names
    with open(A / "motion.bin", "wb") as f:
        f.write(b"PMMO"); f.write(struct.pack("<iif", T, len(names), fps))
        for arr in (jp, jv, rp, rq):
            f.write(np.ascontiguousarray(arr, "<f4").tobytes())

    # ---- FK chain root -> anchor (offline snapshot of the MJCF kinematics; empty when the anchor is the floating base)
    import mujoco
    xml = next((CACHE / "huggingface/hub").rglob("g1-mode_13_15.xml"))
    model = mujoco.MjModel.from_xml_path(str(xml))

    def chain(body_name):
        b = model.body(body_name).id; out = []
        while model.body_parentid[b] != b and model.body(b).name != "pelvis":
            for j in range(model.body_jntadr[b], model.body_jntadr[b] + model.body_jntnum[b]):
                assert model.jnt_type[j] == mujoco.mjtJoint.mjJNT_HINGE
                out.append((model.joint(j).name, model.body_quat[b].copy(), model.jnt_axis[j].copy()))
            b = model.body_parentid[b]
        # a body may carry its offset quat even without joints
        return list(reversed(out))

    def chain_text(body_name):
        b = model.body(body_name).id; items = []
        while model.body(b).name != "pelvis":
            js = list(range(model.body_jntadr[b], model.body_jntadr[b] + model.body_jntnum[b]))
            if not js:
                items.append(("", model.body_quat[b].copy(), np.zeros(3)))
            for j in js:
                items.append((model.joint(j).name, model.body_quat[b].copy(), model.jnt_axis[j].copy()))
            b = model.body_parentid[b]
        assert np.allclose(model.body_quat[model.body("pelvis").id], [1, 0, 0, 0])
        return [f"link {nm or '-'} {fmt(bq)} {fmt(ax)}" for nm, bq, ax in reversed(items)]

    anchor = y["motion"]["anchor_body_name"]
    (A / "fk_chain.txt").write_text(f"# offline FK chain root(pelvis) -> {anchor}: per link  <joint|-> body_quat_wxyz(4) joint_axis(3)\nanchor {anchor}\n" + "\n".join(chain_text(anchor)) + ("\n" if chain_text(anchor) else ""))
    # dev fixture: MuJoCo FK of several bodies for random states
    rng = np.random.default_rng(0); N = 200; data = mujoco.MjData(model)
    free = [i for i in range(model.njnt) if model.jnt_type[i] == mujoco.mjtJoint.mjJNT_FREE][0]; radr = int(model.jnt_qposadr[free])
    jadr = np.asarray([model.joint(n).qposadr[0] for n in names])
    bodies = ["pelvis", "torso_link", "left_wrist_yaw_link", "right_ankle_roll_link", "left_knee_link"]
    qs = rng.uniform(lo, hi, (N, 29)); quats = rng.normal(size=(N, 4)); quats /= np.linalg.norm(quats, axis=1, keepdims=True)
    ref = np.zeros((N, len(bodies), 4))
    for i in range(N):
        data.qpos[radr + 3:radr + 7] = quats[i]; data.qpos[jadr] = qs[i]; mujoco.mj_kinematics(model, data)
        for k, bn in enumerate(bodies): ref[i, k] = data.xquat[model.body(bn).id]
    with open(HERE / "dev/fixtures/fk_ref.bin", "wb") as f:
        f.write(struct.pack("<ii", N, len(bodies)))
        for arr in (qs, quats, ref):
            f.write(np.ascontiguousarray(arr, "<f8").tobytes())
    (HERE / "dev/fixtures/fk_chains.txt").write_text("\n".join(f"body {bn}\n" + "\n".join(chain_text(bn)) for bn in bodies) + "\n")

    # ---- policy parity fixture = the golden state replay made with the Python deployment stack (deploy/partymimic_g1/assets/expected)
    z = np.load(REPO / "deploy/partymimic_g1/assets/expected/selfcheck_ref.npz")
    n = len(z["q"])
    with open(HERE / "dev/fixtures/parity_ref.bin", "wb") as f:
        f.write(struct.pack("<i", n))
        for k in ("q", "dq", "quat", "gyro", "actions", "q_target"):
            f.write(np.ascontiguousarray(z[k], "<f8").tobytes())
    (A / "SHA256SUMS").write_text("".join(f"{sha(A / n)}  {n}\n" for n in ("policy.onnx", "policy_params.txt", "motion.bin", "fk_chain.txt")) +
                                  f"# provenance (dev inputs, not shipped): yaml {FROZEN['policy.yaml']}  ssb_motion.npz {FROZEN['ssb_motion.npz']}\n")

    # ---- frozen hashes compiled into the binary + 3 golden frames for the on-robot selfcheck (source constants, not shipped data files)
    names_h = ("policy.onnx", "policy_params.txt", "motion.bin")
    with open(HERE / "include/pm/frozen.hpp", "w") as f:
        f.write("// generated by dev/export_assets.py: sha256 of the frozen P2 deployment artifacts (checked at every F1+F3 and by selfcheck)\n#pragma once\nnamespace pm {\n")
        for n in names_h:
            f.write(f'constexpr const char* FROZEN_SHA256_{n.split(".")[0].upper()} = "{sha(A / n)}";\n')
        f.write("}  // namespace pm\n")
    G = 3
    def arr(a): return ", ".join(repr(float(x)) for x in np.asarray(a, np.float64).reshape(-1))
    with open(HERE / "include/pm/selfcheck_golden.hpp", "w") as f:
        f.write("// generated by dev/export_assets.py from the Python deployment stack (golden replay, first frames): bit-identical expected on the same ORT version\n#pragma once\nnamespace pm {\nconstexpr int GOLDEN_N = %d;\n" % G)
        for k, nm in (("q", "q"), ("dq", "dq"), ("quat", "quat"), ("gyro", "gyro"), ("actions", "action")):
            f.write(f"constexpr double GOLDEN_{nm.upper()}[] = {{{arr(z[k][:G])}}};\n")
        f.write("}  // namespace pm\n")
    print("OK frames", T, "fps", fps, "onnx", sha(A / "policy.onnx")[:12])


if __name__ == "__main__":
    main()
